import assert from 'node:assert/strict'
import { randomUUID } from 'node:crypto'
export async function taskFocusSmoke(request, expectStatus) {
  const post = (body) => ({method:'POST',body:JSON.stringify(body)})
  const patch = (body) => ({method:'PATCH',body:JSON.stringify(body)})
  const id = randomUUID()
  await request('/tasks',post({id,title:'Three lives smoke',column:'todo',dateKey:'2026-09-07',recurrence:'none',createdAt:Date.now()}))
  const path = `/tasks/${id}`
  await expectStatus(`${path}/focus/start`,post({sessionId:randomUUID()}),422)
  await request(path,patch({doneWhen:'All checks pass'}))
  const renamed = await request(path,patch({title:'Renamed focus smoke'}))
  assert.equal(renamed.task.doneWhen,'All checks pass')
  await expectStatus(path,patch({actualSeconds:999999}),422)
  const sessionId = randomUUID()
  await request(`${path}/focus/start`,post({sessionId}))
  await request(`${path}/focus/start`,post({sessionId}))
  await request(`${path}/focus/pause`,post({sessionId}))
  const children = [1,2].map(n => ({id:randomUUID(),title:`Child ${n}`,doneWhen:`Result ${n}`}))
  await request(`${path}/focus/split`,post({doneWhen:'All checks pass',workSummary:'Initial result',children}))
  await expectStatus(`${path}/focus/start`,post({sessionId:randomUUID()}),409)
  await expectStatus(path,patch({completed:true,confirmResult:true}),409)
  for (const child of children) await request(`/tasks/${child.id}`,patch({completed:true}))
  const list = await request('/tasks')
  assert.equal(list.tasks.find(t=>t.id===id).completed,false)
  await expectStatus(path,patch({completed:true}),422)
  await request(path,patch({completed:true,confirmResult:true}))
  const preserved = await request(path,patch({title:'Completed parent renamed'}))
  assert.equal(preserved.task.completed,true)
  assert.equal(preserved.task.doneWhen,'All checks pass')
  await expectStatus(`/tasks/${children[0].id}`,patch({completed:false}),409)
  // A restored completed child does not invalidate its already confirmed parent.
  await request(`/tasks/${children[1].id}`,{method:'DELETE',body:'{}'})
  await request(`/tasks/${children[1].id}/restore`,post({}))
  await request(path,patch({completed:false}))
  await request(`/tasks/${children[0].id}`,patch({completed:false}))
  await request(path,{method:'DELETE',body:'{}'})
  const trash = await request('/tasks/trash')
  assert.equal(trash.tasks.filter(t=>t.id===id||t.parentTaskId===id).length,3)
  await expectStatus(`/tasks/${children[0].id}/restore`,post({}),409)
  console.log('OK  Three lives: first start, direct-time guard, split, parent confirmation, reopen and cancellation')
}
